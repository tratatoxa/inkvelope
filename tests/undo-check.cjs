const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true, args: ['--disable-background-networking', '--no-proxy-server', '--host-resolver-rules=MAP * ~NOTFOUND'] });
  try {
    const context = await browser.newContext();
    const requests = [], errors = [];
    await context.route('**/*', route => { if (route.request().url().startsWith('file:')) return route.continue(); requests.push(route.request().url()); return route.abort(); });
    await context.addInitScript(() => { Object.defineProperty(navigator, 'clipboard', {value:{writeText:async text=>{window.copiedProject=text;}}}); });
    const page = await context.newPage(); page.setDefaultTimeout(5000);
    page.on('pageerror', e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve(__dirname, '../email-builder.html')).href);
    await page.waitForFunction(()=>document.querySelector('#frame').contentDocument?.querySelector('[data-bid]'));
    // При запуске открыта панель «О конструкторе», работа с блоками — на своей вкладке
    await page.locator('#t-blocks').click();
    assert.equal(await page.locator('#undoChange').isDisabled(),true);
    await page.locator('.toggle').first().click();
    assert.equal(await page.locator('#undoChange').isDisabled(),true);
    const project = {settings:{subject:'UNDO TEST'},blocks:[{type:'text',text:'Original text'},{type:'heading',text:'Second block'}]};
    await page.locator('#openJson').setInputFiles({name:'undo.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))});
    await page.waitForFunction(()=>document.querySelector('input[id$="-subject"]')?.value==='UNDO TEST');
    const readState = () => page.evaluate(async()=>{document.querySelector('#copyJson').click(); return JSON.parse(window.copiedProject);});
    const initial = await readState();
    await page.locator('.toggle').first().click();
    await page.locator('.card textarea').fill('First edit');
    await page.locator('.card textarea').fill('Second edit');
    await page.locator('.card').first().locator('[data-act=del]').click();
    assert.equal((await readState()).blocks.length,1);
    await page.locator('#undoChange').click();
    assert.equal((await readState()).blocks[0].text,'Second edit');
    await page.locator('#undoChange').click();
    assert.deepEqual(await readState(),initial);
    await page.locator('[data-add=heading]').click();
    assert.equal((await readState()).blocks.length,3);
    await page.keyboard.press('Meta+z');
    assert.deepEqual(await readState(),initial);
    await page.locator('.card').last().locator('[data-act=up]').click();
    assert.equal((await readState()).blocks[0].text,'Second block');
    await page.keyboard.press('Control+z');
    assert.deepEqual(await readState(),initial);
    await page.locator('#t-style').click();
    await page.getByLabel('Тема письма',{exact:true}).fill('Changed subject');
    await page.keyboard.press('Control+z');
    assert.equal(await page.getByLabel('Тема письма',{exact:true}).inputValue(),'UNDO TEST');
    await page.locator('#themeToggle').click();
    await page.locator('#clearAll').click(); await page.locator('#clearAll').click();
    assert.notEqual((await readState()).settings.subject,'UNDO TEST');
    await page.locator('#undoChange').click();
    assert.deepEqual(await readState(),initial);
    assert.equal(await page.evaluate(()=>document.documentElement.dataset.theme),'dark');
    await page.locator('#t-import').click();
    await page.locator('#importFile').setInputFiles({name:'import.html',mimeType:'text/html',buffer:Buffer.from('<p>Imported replacement</p>')});
    await page.locator('[data-relayout]').click();
    assert.ok((await readState()).blocks.some(b=>b.text?.includes('Imported replacement')));
    await page.locator('#undoChange').click();
    assert.deepEqual(await readState(),initial);
    assert.equal(await page.locator('[data-undo]').count(),0);
    assert.deepEqual(requests,[]);assert.deepEqual(errors,[]);
    console.log('PASS: selection creates no history; grouped typing, deletion, addition, reordering, settings, reset and import can be undone; Cmd/Ctrl+Z work; theme preserved; no network or JS errors.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
